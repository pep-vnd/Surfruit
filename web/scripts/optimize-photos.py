"""Generate committed responsive WebP assets. Requires Pillow; run only when photos change."""
import json
import re
from pathlib import Path
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / 'assets'
archive = root.parent / 'wetransfer_surfruit_2026-10-12_0829'
sources = {}
for line in (root / 'docs/photo-sources.md').read_text().splitlines():
    match = re.match(r'\| `([a-z-]+)-\*\.webp` \| `([^`]+)`', line)
    if match and (archive / match[2]).is_file():
        sources[match[1]] = archive / match[2]
groups = {}
for file in assets.glob('*.webp'):
    match = re.fullmatch(r'(.+)-(\d+)\.webp', file.name)
    if match:
        groups.setdefault(match[1], []).append(file)
output = assets / 'photos'
output.mkdir(exist_ok=True)
manifest = {}
before = after = 0
for name, files in sorted(groups.items()):
    source = sources.get(name) or max(files, key=lambda p: Image.open(p).width)
    im = ImageOps.exif_transpose(Image.open(source)).convert('RGB')
    maximum = min(im.width, max(int(p.stem.rsplit('-', 1)[1]) for p in files), 1800)
    widths = sorted(set([w for w in [480, 700, 1000, 1400, 1800] if w < maximum] + [maximum]))
    variants = []
    for width in widths:
        height = round(im.height * width / im.width)
        resized = im.resize((width, height), Image.Resampling.LANCZOS)
        target = output / f'{name}-{width}.webp'
        resized.save(target, 'WEBP', quality=80, method=6)
        variants.append({'width':width, 'height':height, 'file':f'photos/{target.name}'})
    manifest[name] = variants
    old = max(files, key=lambda p: int(p.stem.rsplit('-', 1)[1]))
    before += old.stat().st_size
    after += (output / f'{name}-{maximum}.webp').stat().st_size
(root / 'src/photo-manifest.mjs').write_text('// Generated by scripts/optimize-photos.py\nexport const photos = ' + json.dumps(manifest, separators=(',', ':')) + ';\n')
print(f'{len(groups)} photos: largest variants {before:,} -> {after:,} bytes ({(1-after/before)*100:.1f}% reduction).')
